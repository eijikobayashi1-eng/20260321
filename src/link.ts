import * as crypto from "crypto";
import * as http from "http";
import * as fs from "fs";
import * as path from "path";
import * as os from "os";

/**
 * Represents a linked session between desktop and browser Claude Code.
 */
export interface LinkSession {
  /** Unique identifier for this link session */
  sessionId: string;
  /** The original link token used to establish the connection */
  token: string;
  /** OAuth-style access token received from browser */
  accessToken?: string;
  /** Refresh token for renewing the session */
  refreshToken?: string;
  /** Session expiry timestamp (ISO 8601) */
  expiresAt?: string;
  /** Browser-side user info */
  userInfo?: {
    email?: string;
    userId?: string;
    displayName?: string;
  };
  /** When the session was established (ISO 8601) */
  linkedAt: string;
  /** Callback URL used for this session */
  callbackUrl: string;
}

/**
 * Result of a callback received by the local HTTP server.
 */
export interface CallbackResult {
  success: boolean;
  session?: LinkSession;
  error?: string;
}

/** Default port for the local callback server */
export const DEFAULT_LINK_PORT = 10999;

/** Base URL for the Claude.ai linking endpoint */
export const CLAUDE_LINK_BASE_URL = "https://claude.ai/code/link";

/** Path to persist the linked session */
const SESSION_FILE_PATH = path.join(os.homedir(), ".claude", "browser-link.json");

/**
 * Generates a cryptographically secure random token for the link flow.
 * Uses 32 bytes of random data encoded as a URL-safe base64 string.
 */
export function generateLinkToken(): string {
  const bytes = crypto.randomBytes(32);
  // URL-safe base64 encoding
  return bytes.toString("base64url");
}

/**
 * Constructs the browser-facing URL that initiates the link flow.
 *
 * @param token   The link token generated by generateLinkToken()
 * @param port    The port the local callback server is listening on
 * @returns       Full URL to open in a browser
 */
export function buildLinkUrl(token: string, port: number = DEFAULT_LINK_PORT): string {
  const callbackUrl = `http://localhost:${port}/callback`;
  const params = new URLSearchParams({
    token,
    callback: callbackUrl,
  });
  return `${CLAUDE_LINK_BASE_URL}?${params.toString()}`;
}

/**
 * Starts a local HTTP server that waits for the browser callback.
 * The server listens for a single request at /callback, then shuts down.
 *
 * @param port    Port to listen on (default: DEFAULT_LINK_PORT)
 * @param token   Expected token to validate the callback
 * @returns       Promise that resolves with CallbackResult when callback is received
 */
export function startLinkServer(port: number, token: string): Promise<CallbackResult> {
  return new Promise((resolve) => {
    const server = http.createServer((req, res) => {
      const url = new URL(req.url ?? "/", `http://localhost:${port}`);

      if (url.pathname !== "/callback") {
        res.writeHead(404, { "Content-Type": "text/plain" });
        res.end("Not found");
        return;
      }

      // Parse callback parameters
      const receivedToken = url.searchParams.get("token");
      const accessToken = url.searchParams.get("access_token") ?? undefined;
      const refreshToken = url.searchParams.get("refresh_token") ?? undefined;
      const expiresAt = url.searchParams.get("expires_at") ?? undefined;
      const email = url.searchParams.get("email") ?? undefined;
      const userId = url.searchParams.get("user_id") ?? undefined;
      const displayName = url.searchParams.get("display_name") ?? undefined;
      const errorParam = url.searchParams.get("error");

      // Handle error from browser
      if (errorParam) {
        const htmlError = `<!DOCTYPE html>
<html>
<head><title>Link Failed - Claude Code</title></head>
<body>
  <h1>Link Failed</h1>
  <p>The browser returned an error: <strong>${escapeHtml(errorParam)}</strong></p>
  <p>You can close this tab.</p>
</body>
</html>`;
        res.writeHead(400, { "Content-Type": "text/html" });
        res.end(htmlError);
        server.close();
        resolve({ success: false, error: errorParam });
        return;
      }

      // Validate token to prevent CSRF
      if (receivedToken !== token) {
        const htmlInvalid = `<!DOCTYPE html>
<html>
<head><title>Invalid Token - Claude Code</title></head>
<body>
  <h1>Invalid Token</h1>
  <p>The token did not match. This callback may be stale or tampered with.</p>
  <p>You can close this tab and try linking again.</p>
</body>
</html>`;
        res.writeHead(403, { "Content-Type": "text/html" });
        res.end(htmlInvalid);
        server.close();
        resolve({ success: false, error: "Token mismatch – possible CSRF or stale callback" });
        return;
      }

      // Build session
      const session: LinkSession = {
        sessionId: crypto.randomUUID(),
        token,
        accessToken,
        refreshToken,
        expiresAt,
        userInfo:
          email ?? userId ?? displayName
            ? { email, userId, displayName }
            : undefined,
        linkedAt: new Date().toISOString(),
        callbackUrl: `http://localhost:${port}/callback`,
      };

      const htmlSuccess = `<!DOCTYPE html>
<html>
<head><title>Linked - Claude Code</title></head>
<body>
  <h1>Successfully Linked!</h1>
  <p>Your browser session is now connected to the desktop Claude Code CLI.</p>
  ${email ? `<p>Signed in as: <strong>${escapeHtml(email)}</strong></p>` : ""}
  <p>You can close this tab and return to your terminal.</p>
</body>
</html>`;

      res.writeHead(200, { "Content-Type": "text/html" });
      res.end(htmlSuccess);

      // Close the server after sending the response
      server.close(() => {
        resolve({ success: true, session });
      });
    });

    server.on("error", (err: NodeJS.ErrnoException) => {
      if (err.code === "EADDRINUSE") {
        resolve({
          success: false,
          error: `Port ${port} is already in use. Please free the port and try again.`,
        });
      } else {
        resolve({ success: false, error: err.message });
      }
    });

    server.listen(port, "127.0.0.1", () => {
      // Server is ready
    });
  });
}

/**
 * Generates the link URL and attempts to open it in the default browser.
 * Falls back to printing the URL if the browser cannot be opened.
 *
 * @param token   Link token to embed in the URL
 * @param port    Callback port (default: DEFAULT_LINK_PORT)
 */
export async function openBrowserLink(
  token: string,
  port: number = DEFAULT_LINK_PORT
): Promise<void> {
  const linkUrl = buildLinkUrl(token, port);

  console.log("\nTo link your browser session, open the following URL:");
  console.log(`\n  ${linkUrl}\n`);

  try {
    // Dynamically import "open" so the rest of the module works without it
    // eslint-disable-next-line @typescript-eslint/no-var-requires
    const openModule = await import("open");
    const openFn = openModule.default ?? openModule;
    await (openFn as (url: string) => Promise<unknown>)(linkUrl);
    console.log("(Attempting to open in your default browser…)");
  } catch {
    console.log(
      "(Could not open browser automatically – please copy the URL above into your browser.)"
    );
  }
}

/**
 * Persists a LinkSession to ~/.claude/browser-link.json.
 * The directory is created if it does not exist.
 * File permissions are set to 0o600 (owner read/write only).
 *
 * @param session   The session object to save
 */
export function saveLinkSession(session: LinkSession): void {
  const dir = path.dirname(SESSION_FILE_PATH);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true, mode: 0o700 });
  }

  const data = JSON.stringify(session, null, 2);
  fs.writeFileSync(SESSION_FILE_PATH, data, { encoding: "utf8", mode: 0o600 });
}

/**
 * Loads a previously saved LinkSession from ~/.claude/browser-link.json.
 *
 * @returns The persisted LinkSession, or null if none exists or the file is unreadable.
 */
export function loadLinkSession(): LinkSession | null {
  if (!fs.existsSync(SESSION_FILE_PATH)) {
    return null;
  }

  try {
    const raw = fs.readFileSync(SESSION_FILE_PATH, "utf8");
    return JSON.parse(raw) as LinkSession;
  } catch {
    return null;
  }
}

/**
 * Removes the persisted session file.
 */
export function removeLinkSession(): void {
  if (fs.existsSync(SESSION_FILE_PATH)) {
    fs.unlinkSync(SESSION_FILE_PATH);
  }
}

/**
 * Returns the file system path where the session is stored.
 */
export function getSessionFilePath(): string {
  return SESSION_FILE_PATH;
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}
